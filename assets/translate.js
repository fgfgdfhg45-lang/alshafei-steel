function getCurrentLang(){
  return document.body.dataset.lang || 'ar';
}

function setLanguage(lang){
  const elements = document.querySelectorAll('h1,h2,h3,h4,p,a,button,span,label,small,li,th,td,footer');
  elements.forEach(el=>{
    if(el.closest('script,style,noscript')) return;
    if(el.children.length > 0) return;

    if(!el.dataset.originalText){
      el.dataset.originalText = el.innerText.trim();
    }
    const original = el.dataset.originalText;
    if(!original) return;

    if(lang==='ar'){
      el.innerText = original;
    } else {
      const translation = FULL_DICT[original];
      if(translation && translation[lang]){
        el.innerText = translation[lang];
      }
    }
  });

  document.querySelectorAll('input,textarea').forEach(el=>{
    if(!el.dataset.originalPh) el.dataset.originalPh = el.placeholder;
    const phMap={
      'اسمك':                             {en:'Your Name'},
      'رقم الهاتف':                        {en:'Phone Number'},
      'البريد الإلكتروني':                 {en:'Email Address'},
      'اكتب تفاصيل طلبك من المنتجات...':{en:'Write your product request details...'},
    };
    if(lang!=='ar'){
      const t=phMap[el.dataset.originalPh];
      if(t && t[lang]) el.placeholder=t[lang];
    } else {
      el.placeholder=el.dataset.originalPh;
    }
  });

  if(lang==='ar'){
    document.documentElement.lang='ar';
    document.documentElement.dir='rtl';
    document.body.style.fontFamily="'Cairo',sans-serif";
  } else {
    document.documentElement.lang=lang;
    document.documentElement.dir='ltr';
    document.body.style.fontFamily="'Inter',sans-serif";
  }

  const orderBtnLabels = { ar: 'أضف للسلة', en: 'Add to Cart' };
  document.querySelectorAll('.order-btn').forEach(btn => {
    const orig = btn.dataset.originalText || btn.innerText.trim();
    if(!btn.dataset.originalText) btn.dataset.originalText = orig;
    btn.innerText = orderBtnLabels[lang];
  });

  document.body.dataset.lang = lang;

  const h1Translations = {
    ar: { prefix: 'رواد تصنيع', suffix: 'الحديثة' },
    en: { prefix: 'Leaders in Manufacturing', suffix: 'Modern' }
  };
  const t = h1Translations[lang] || h1Translations['ar'];
  const pfx = document.getElementById('h1-prefix');
  const sfx = document.getElementById('h1-suffix');
  if(pfx) pfx.textContent = t.prefix;
  if(sfx) sfx.textContent = t.suffix;
}

// ===== الكلمة المتحركة (Typewriter) في عنوان الهيرو =====
(function(){
  const wordsByLang={
    ar:['المنتجات الصناعية','خطوط الإنتاج','معدات التغليف','ماكينات الطحن'],
    en:['Industrial Products','Production Lines','Packaging Equipment','Grinding Machines']
  };
  let wi=0,ci=0,deleting=false;

  function tick(){
    const el=document.getElementById('typewriter-text');
    if(!el)return;
    const lang=getCurrentLang();
    const words=wordsByLang[lang]||wordsByLang['ar'];
    const word=words[wi%words.length];
    if(!deleting){
      el.textContent=word.substring(0,ci+1);
      ci++;
      if(ci===word.length){
        setTimeout(()=>{deleting=true;tick();},1800);
        return;
      }
    }else{
      el.textContent=word.substring(0,ci-1);
      ci--;
      if(ci===0){
        deleting=false;
        wi=(wi+1)%words.length;
      }
    }
    setTimeout(tick,deleting?60:100);
  }
  document.addEventListener('DOMContentLoaded', function(){
    setTimeout(tick,600);
  });
})();
