# ---------------------------------------------------------------- Firestore ----------
def fv(v):
    for k in ('stringValue', 'integerValue', 'booleanValue', 'timestampValue'):
        if k in v: return v[k]
    return ''

def fetch_live():
    docs, token = [], None
    while True:
        url = f'https://firestore.googleapis.com/v1/projects/{PROJECT}/databases/(default)/documents/machines_new?pageSize=200'
        if token: url += '&pageToken=' + urllib.parse.quote(token)
        with urllib.request.urlopen(url, timeout=30) as r: data = json.load(r)
        docs += data.get('documents', []); token = data.get('nextPageToken')
        if not token: return {'documents': docs}

def load(path):
    data = json.load(open(path, encoding='utf-8')) if path else fetch_live()
    out = []
    for d in data.get('documents', []):
        f = {k: fv(v) for k, v in d.get('fields', {}).items()}
        f['id'] = d['name'].rsplit('/', 1)[1]; f['_created'] = d.get('createTime', ''); f['_updated'] = (d.get('updateTime') or d.get('createTime') or '')[:10]
        if str(f.get('name', '')).strip(): out.append(f)
    return sorted(out, key=lambda x: (x['_created'], x['id']))

# ---------------------------------------------------------------- helpers ----------
def slugify(s):
    s = re.sub(r'(?i)\bmodel\b', '', str(s or '')).lower()
    return re.sub(r'[^a-z0-9]+', '-', s).strip('-')[:60]

def parse_specs(text):
    rows = []
    for line in str(text or '').splitlines():
        line = line.strip()
        if not line: continue
        m = re.match(r'^(.{1,60}?)\s*[:：]\s*(.+)$', line)
        rows.append((m.group(1), m.group(2)) if m else (None, line))
    return rows

def paragraphs(text):
    return [p.strip() for p in re.split(r'\n\s*\n', str(text or '')) if p.strip()]

def read(p): return open(p, encoding='utf-8').read()
def write(p, s):
    os.makedirs(os.path.dirname(p) or '.', exist_ok=True); open(p, 'w', encoding='utf-8').write(s)

def ld_dump(obj):
    return json.dumps(obj, ensure_ascii=False, indent=2).replace('<', '\\u003c').replace('>', '\\u003e').replace('&', '\\u0026')

def short_title(name):
    full = f'{name} — المواصفات والسعر | الشافعي ستيل'
    return full if len(full) <= MAXTITLE else f'{name} | الشافعي ستيل'

def safe_img(u):
    u = str(u or '').strip()
    return u if re.match(r'^https?://[^\s"\'<>]+$', u) else DEFAULT_IMG

