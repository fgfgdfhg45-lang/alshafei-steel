def card_html(d, folder, slug, key):
    name, model = str(d['name']).strip(), re.sub(r'(?i)^model\s*', '', str(d.get('model', '')).strip()).strip()
    img = safe_img(d.get('img')); desc = str(d.get('desc', '')).strip(); href = f'{slug}.html'
    return (f'<div class="machine-card" data-category="{e(key)}">\n<img loading="lazy" decoding="async" src="{e(img)}" alt="{e(name)} — الشافعي ستيل">\n'
            f'<div class="machine-info">\n<a href="{e(href)}" style="text-decoration:none;"><h3 style="color:#fff;">{e(name)}</h3></a>\n'
            + (f'<span class="machine-model">Model {e(model)}</span>\n' if model else '') + '<div class="machine-divider"></div>\n'
            + (f'<p>{e(desc)}</p>\n' if desc else '')
            + f'<a href="{e(href)}" class="order-btn" style="margin-top:0;background:transparent;border:1px solid var(--secondary);">التفاصيل والسعر ←</a>\n</div>\n</div>')

def update_index(folder, cards, check):
    p = f'{folder}/index.html'; s = read(p); body = f'{DYN_S}\n{cards}\n{DYN_E}'
    if DYN_S in s:
        s2 = re.sub(re.escape(DYN_S) + r'.*?' + re.escape(DYN_E), lambda m: body, s, count=1, flags=re.S)
    elif cards:
        g = s.index('class="machines-grid"'); m = re.search(r'</div>(\s*</section>)', s[g:]); idx = g + m.start()
        s2 = s[:idx] + body + '\n' + s[idx:]
    else: return False
    if s2 != s and not check: write(p, s2)
    return s2 != s

def update_sitemap(entries, check):
    s = read('sitemap.xml')
    block = '  <!-- DYN-MACHINES -->\n' + ''.join(
        f'  <url>\n    <loc>{SITE}/{p}</loc>\n    <lastmod>{lm}</lastmod>\n    <changefreq>monthly</changefreq>\n    <priority>0.7</priority>\n  </url>\n' for p, lm in entries) + '  <!-- /DYN-MACHINES -->\n'
    if '<!-- DYN-MACHINES -->' in s: s2 = re.sub(r'  <!-- DYN-MACHINES -->.*?<!-- /DYN-MACHINES -->\n', lambda m: block, s, count=1, flags=re.S)
    else: s2 = s.replace('</urlset>', block + '</urlset>', 1)
    if s2 != s and not check: write('sitemap.xml', s2)
    return s2 != s

def update_search(new_items, old_paths, check):
    s = read('assets/search-data.js'); m = re.search(r'window\.SITE_SEARCH_DATA = (\[.*\]);', s, re.S)
    data = [x for x in json.loads(m.group(1)) if x['path'] not in old_paths and x['path'] not in {n['path'] for n in new_items}] + new_items
    s2 = s[:m.start()] + 'window.SITE_SEARCH_DATA = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';' + s[m.end():]
    if s2 != s and not check: write('assets/search-data.js', s2)
    return s2 != s

# ---------------------------------------------------------------- main ----------
def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--dry-run', action='store_true'); ap.add_argument('--from-file')
    a = ap.parse_args(); check = a.dry_run
    docs = load(a.from_file)
    manifest = json.load(open(MANIFEST, encoding='utf-8')) if os.path.exists(MANIFEST) else {}
    print(f'ماكينات في Firestore: {len(docs)} | مولّدة قبل كده: {len(manifest)}')
    taken = lambda folder, slug, me: os.path.exists(f'{folder}/{slug}.html') and manifest.get(me, {}).get('path') != f'{folder}/{slug}.html'
    new_manifest, by_folder, sm_entries, search_items = {}, {}, [], []
    for d in docs:
        key = d.get('cat') if d.get('cat') in FOLDERS else 'other'; folder = FOLDERS[key]
        if not os.path.exists(f'{folder}/index.html'): print('!! مفيش صفحة نوع:', folder); continue
        cat_label = bn.h1(f'{folder}/index.html') or folder
        old = manifest.get(d['id'])
        slug = slugify(d.get('slug')) or (old['path'].split('/')[-1][:-5] if old and old['path'].startswith(folder + '/') else '') \
               or slugify(d.get('model')) or 'machine-' + d['id'][:8].lower()
        if taken(folder, slug, d['id']): slug += '-' + d['id'][:4].lower()
        path = f'{folder}/{slug}.html'
        page = build_page(d, folder, slug, cat_label, path)
        if not check: write(path, page)
        new_manifest[d['id']] = {'path': path, 'name': d['name']}
        by_folder.setdefault((folder, key), []).append(card_html(d, folder, slug, key))
        sm_entries.append((path, d['_updated'] or datetime.date.today().isoformat()))
        search_items.append({'name': str(d['name']).strip(), 'model': ('Model ' + re.sub(r'(?i)^model\s*', '', str(d.get('model', ''))).strip()) if d.get('model') else '',
                             'cat': cat_label, 'img': safe_img(d.get('img')), 'path': path})
        print(('[dry] ' if check else '') + f'{d["name"]}  ->  {path}')
    # delete pages of machines removed from the dashboard
    for mid, info in manifest.items():
        if mid not in new_manifest and os.path.exists(info['path']):
            print(('[dry] ' if check else '') + 'مسح صفحة ماكينة اتمسحت من اللوحة:', info['path'])
            if not check: os.remove(info['path'])
    # cards on the category pages (also empties folders that no longer have generated machines)
    for folder in sorted(set(FOLDERS.values())):
        cards = '\n'.join(c for (f, _k), cs in by_folder.items() if f == folder for c in cs)
        if update_index(folder, cards, check): print(('[dry] ' if check else '') + 'تحديث كروت صفحة النوع:', folder)
    old_paths = {i['path'] for i in manifest.values()}
    update_sitemap(sm_entries, check); update_search(search_items, old_paths, check)
    if not check:
        write(MANIFEST, json.dumps(new_manifest, ensure_ascii=False, indent=1))
        bn.main(False)
        for p in ('machines/index.html', 'en/machines/index.html'): bcp.process(p, False)
    print('خلصنا.' + (' (معاينة فقط — مفيش حاجة اتكتبت)' if check else ' ارفع الملفات المتغيّرة على الاستضافة.'))

if __name__ == '__main__':
    main()
