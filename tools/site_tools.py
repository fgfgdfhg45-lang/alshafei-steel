#!/usr/bin/env python3
"""
Helper for keeping the Arabic and English pages in sync.

  python3 tools/site_tools.py parity
      Compares the structure (sections, ids, headings) of every Arabic page
      with its English twin under en/ and lists the pages that differ.

  python3 tools/site_tools.py replace "OLD" "NEW" [--apply] [--en-only|--ar-only]
      Finds OLD in every page and replaces it with NEW. Without --apply it only
      shows how many pages would change (dry run).
"""
import glob, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def pages():
    out = []
    for f in glob.glob(os.path.join(ROOT, '**', '*.html'), recursive=True):
        rel = os.path.relpath(f, ROOT).replace(os.sep, '/')
        if rel.startswith('assets/') or rel.startswith('tools/') or rel.startswith('google'):
            continue
        out.append(rel)
    return sorted(out)

def is_en(p):
    return p.startswith('en/') or p.startswith('blog/en/')

def twin_of(p, allp):
    """English twin of an Arabic page: en/<path> or (for blog posts) blog/en/<name>."""
    cands = ['en/' + p]
    if p.startswith('blog/'):
        cands.append('blog/en/' + p[len('blog/'):])
    for c in cands:
        if c in allp:
            return c
    return None

def skeleton(path):
    s = open(os.path.join(ROOT, path), encoding='utf-8', errors='ignore').read()
    s = re.sub(r'<(script|style|noscript)\b.*?</\1>', '', s, flags=re.S)
    s = re.sub(r'<!--DYN-CARDS-->.*?<!--/DYN-CARDS-->', '', s, flags=re.S)   # كروت الماكينات المولّدة من اللوحة (عربي بس)
    sk = []
    for m in re.finditer(r'<(section|header|footer|nav|main|h1|h2|h3|form)\b([^>]*)>', s):
        i = re.search(r'id="([^"]*)"', m.group(2))
        sk.append(m.group(1) + ('#' + i.group(1) if i else ''))
    for m in re.finditer(r'\bid="([^"]*)"', s):
        sk.append('#' + m.group(1))
    return sorted(sk)

def parity():
    allp = pages()
    gen = lambda p: 'GENERATED by tools/sync_machines.py' in open(os.path.join(ROOT, p), encoding='utf-8', errors='ignore').read()
    ar = [p for p in allp if not is_en(p) and not gen(p)]
    bad = missing = 0
    for p in ar:
        twin = twin_of(p, allp)
        if twin is None:
            print('MISSING EN TWIN:', p); missing += 1; continue
        a, b = skeleton(p), skeleton(twin)
        if a != b:
            only_a = [x for x in a if x not in b][:5]
            only_b = [x for x in b if x not in a][:5]
            print('DIFFERENT:', p, '<->', twin, '| only AR:', only_a, '| only EN:', only_b, '| items AR/EN:', len(a), len(b)); bad += 1
    twins = {twin_of(p, allp) for p in ar}
    for p in allp:
        if is_en(p) and p not in twins:
            print('MISSING AR TWIN:', p); missing += 1
    print(f'\n{len(ar)} Arabic pages checked | {bad} differ | {missing} missing twin')

def replace(old, new, apply, only):
    n = 0
    for p in pages():
        if only == 'en' and not is_en(p): continue
        if only == 'ar' and is_en(p): continue
        f = os.path.join(ROOT, p)
        s = open(f, encoding='utf-8', errors='ignore').read()
        if old in s:
            n += 1
            if apply:
                open(f, 'w', encoding='utf-8').write(s.replace(old, new))
    print(('Replaced in' if apply else 'Would replace in'), n, 'pages' + ('' if apply else '  (add --apply to write)'))

if __name__ == '__main__':
    a = sys.argv[1:]
    if not a: print(__doc__)
    elif a[0] == 'parity': parity()
    elif a[0] == 'replace' and len(a) >= 3:
        only = 'en' if '--en-only' in a else 'ar' if '--ar-only' in a else None
        replace(a[1], a[2], '--apply' in a, only)
    else: print(__doc__)
